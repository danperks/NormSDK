//! `cargo xtask docs [--check]`: renders docs/COMMANDS.md from the annotated
//! catalog and the replies recorded from the emulated stock firmware.

use std::fmt::Write as _;
use std::path::{Path, PathBuf};
use std::{env, fs, process};

use normsdk::{
    Action, Category, CommandKind, Evidence, FirmwareSupport, FrameFormat, WriteChannel,
};
use serde_json::Value;

fn root() -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR"))
        .ancestors()
        .nth(2)
        .unwrap()
        .to_path_buf()
}

fn hex(data: &[u8]) -> String {
    normsdk::hex_string(data.to_vec())
}

fn code(byte: u8) -> String {
    format!("`0x{byte:02X}`")
}

fn action(a: Option<Action>) -> &'static str {
    match a {
        Some(Action::Check) => "check `70`",
        Some(Action::Set) => "set `71`",
        Some(Action::CheckResponse) => "push `80`",
        Some(Action::SetResponse) => "reply `81`",
        Some(Action::Other { .. }) => "other",
        None => "—",
    }
}

fn evidence(e: Evidence) -> &'static str {
    match e {
        Evidence::IosObserved => "official iOS app",
        Evidence::Android6e => "Android 6E stack",
        Evidence::AndroidLegacy6f => "Android 6F stack",
        Evidence::Rewrite => "NormConnect rewrite",
        Evidence::FirmwarePatch => "NormCrack patched firmware",
    }
}

fn firmware(f: &FirmwareSupport) -> String {
    match f {
        FirmwareSupport::Stock => "handled".into(),
        FirmwareSupport::NoStockHandler => "no handler (ack status 2)".into(),
        FirmwareSupport::Ignored6e => "ignored (6E)".into(),
        FirmwareSupport::Patched { feature } => format!("patched: {feature}"),
    }
}

fn category(c: Category) -> &'static str {
    match c {
        Category::Pairing => "Pairing and identity",
        Category::Time => "Time and profile",
        Category::Settings => "Settings",
        Category::Calibration => "Hand calibration",
        Category::Health => "Health data",
        Category::Alarms => "Alarms and reminders",
        Category::Weather => "Weather",
        Category::Notifications => "Notifications",
        Category::Media => "Media",
        Category::Remote => "Remote replies",
        Category::WatchFace => "Watch faces and carousel",
        Category::PatchedFirmware => "Patched firmware",
        Category::System => "System",
    }
}

fn emulator_cell(result: Option<&Value>) -> String {
    let Some(r) = result else {
        return "not run".into();
    };
    let outcome = r["outcome"].as_str().unwrap_or("");
    match outcome.split(':').next() {
        Some("ack") => format!("ack status {}", &outcome[4..]),
        Some("reply") => "reply".into(),
        Some("sent") => "sent, no reply".into(),
        Some("timeout") => "no reply".into(),
        _ => outcome.into(),
    }
}

fn render() -> String {
    let results_path = root().join("docs/emulator-results.json");
    let results: Value = fs::read_to_string(&results_path)
        .ok()
        .and_then(|s| serde_json::from_str(&s).ok())
        .unwrap_or(Value::Null);
    let commands = &results["commands"];

    let mut out = String::new();
    out.push_str("# Command reference\n\n");
    out.push_str(
        "Generated by `cargo xtask docs` from the annotated catalog in \
         [`crates/norm-sdk/src/catalog.rs`](../crates/norm-sdk/src/catalog.rs), merged with the \
         replies recorded from the stock firmware running under emulation \
         ([`tests/emulator`](../tests/emulator)). Do not edit by hand.\n\n",
    );
    out.push_str(
        "Frames are `6F cmd action len_lo len_hi payload… 8F` or `6E 01 cmd payload… 8F`. \
         Every 6F set is answered with the generic ack `01 81 [cmd, status]` (status 0 = applied, \
         1 = rejected or no data, 2 = no handler). The stock firmware ignores 6E frames and drops \
         6F frames with an empty payload.\n\n",
    );
    if let Some(fw) = results["firmware"].as_str() {
        let _ = writeln!(out, "Emulator column: `{fw}`.\n");
    }

    out.push_str("| ID | Frame | Code | Action | Reply | Stock firmware | Emulator |\n|---|---|---|---|---|---|---|\n");
    for kind in CommandKind::ALL {
        let s = kind.spec();
        let frame = if s.format == FrameFormat::Frame6f {
            "6F"
        } else {
            "6E"
        };
        let reply = s.response_command.map(code).unwrap_or_else(|| "—".into());
        let _ = writeln!(
            out,
            "| [`{}`](#{}) | {} | {} | {} | {} | {} | {} |",
            s.id,
            s.id.replace('.', ""),
            frame,
            code(s.command),
            action(s.action),
            reply,
            firmware(&s.firmware),
            emulator_cell(commands.get(&s.id)),
        );
    }

    let mut current = None;
    for kind in CommandKind::ALL {
        let s = kind.spec();
        if current != Some(s.category) {
            current = Some(s.category);
            let _ = writeln!(out, "\n## {}\n", category(s.category));
        }
        let _ = writeln!(
            out,
            "### `{}`\n\n**{}**{}\n",
            s.id,
            s.title,
            if s.summary.is_empty() {
                String::new()
            } else {
                format!(". {}", s.summary)
            }
        );
        let channel = match s.write_channel {
            WriteChannel::Primary => "`8001`",
            WriteChannel::Remote => "`8003` (remote)",
        };
        let frame = if s.format == FrameFormat::Frame6f {
            "6F"
        } else {
            "6E"
        };
        let _ = writeln!(out, "| | |\n|---|---|");
        let _ = writeln!(
            out,
            "| Frame | {frame} {} {}, written to {channel} |",
            code(s.command),
            action(s.action)
        );
        let _ = writeln!(out, "| Request | {} |", s.request_layout);
        let _ = writeln!(out, "| Response | {} |", s.response_layout);
        if s.expects_response {
            let mut reply = s.response_command.map(code).unwrap_or_default();
            for alt in &s.alternate_response_commands {
                let _ = write!(reply, " or {}", code(*alt));
            }
            let multi = if s.multi_response {
                ", one frame per record"
            } else {
                ""
            };
            let _ = writeln!(
                out,
                "| Completes on | {reply}{multi}; timeout {} ms |",
                s.timeout_ms
            );
        }
        let _ = writeln!(out, "| Evidence | {} |", evidence(s.evidence));
        let _ = writeln!(out, "| Stock firmware | {} |", firmware(&s.firmware));
        let example = kind.example();
        let frames: Vec<String> = example
            .frames()
            .iter()
            .map(|f| format!("`{}`", hex(&f.data)))
            .collect();
        let shown = if frames.len() > 2 {
            format!("{} … ({} frames)", frames[0], frames.len())
        } else {
            frames.join("<br>")
        };
        let _ = writeln!(out, "| Example | {shown} |");
        if let Some(r) = commands.get(&s.id) {
            let received: Vec<String> = r["received"]
                .as_array()
                .map(|a| {
                    a.iter()
                        .filter_map(Value::as_str)
                        .map(|f| format!("`{f}`"))
                        .collect()
                })
                .unwrap_or_default();
            let mut cell = if received.is_empty() {
                "no reply".to_string()
            } else {
                received.join("<br>")
            };
            if let Some(resp) = r["response"].as_str() {
                let _ = write!(cell, "<br>→ `{}`", resp.replace('|', "\\|"));
            }
            let _ = writeln!(out, "| Emulator | {cell} |");
        }
        if !s.notes.is_empty() {
            let _ = writeln!(out, "\n{}", s.notes);
        }
        out.push('\n');
    }
    out
}

fn main() {
    let args: Vec<String> = env::args().skip(1).collect();
    match args.first().map(String::as_str) {
        Some("docs") => {
            let path = root().join("docs/COMMANDS.md");
            let rendered = render();
            if args.iter().any(|a| a == "--check") {
                if fs::read_to_string(&path).ok().as_deref() != Some(rendered.as_str()) {
                    eprintln!("docs/COMMANDS.md is stale; run `cargo xtask docs`");
                    process::exit(1);
                }
            } else {
                fs::write(&path, rendered).expect("write docs/COMMANDS.md");
                println!("wrote {}", path.display());
            }
        }
        _ => {
            eprintln!("usage: cargo xtask docs [--check]");
            process::exit(2);
        }
    }
}
